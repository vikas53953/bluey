"""Compile list: what MSBuild really compiles in src/ must be exactly what scripts/quality/ratchet.py reads.

  python -I scripts/quality/compile_list.py              CI: build every src/<Name>/<Name>.csproj and compare
  python -I scripts/quality/compile_list.py --self-test  CI: prove the comparison on planted samples

Build files decide what is compiled: a <Compile Include="../x.txt"/>, an <Import>ed props file, a target that adds an
item, a <Using Include="System.GC" Static="true"/>. The ratchet reads files, not build logic, so this check asks MSBuild
itself (the Compile and Using items after the Build target ran) and fails when:
  - a compiled file is not one the ratchet scans for that project (outside the project, not a .cs file, git-ignored);
  - a file the ratchet scans for that project is not compiled (the ratchet would count code that does not ship);
  - a file generated under the project's obj/ is not one of the known SDK / WPF outputs;
  - a XAML page holds an x:Code block (C# hidden inside XAML, which the ratchet never reads);
  - a <Using> item is static or an alias (the ratchet cannot see through it; write a normal `using` in a .cs file);
  - a <ProjectReference> points outside src/<Name>/<Name>.csproj (that code ships with the app but nothing judges it).
Exit 1 on a finding, 2 when the check could not run. Rule text: docs/quality/RULES.md#compile-list.
"""
import importlib.util
import json
import pathlib
import re
import subprocess
import sys

root = pathlib.Path(__file__).resolve().parent.parent.parent
RULES_DOC = 'docs/quality/RULES.md#compile-list'
BUILD = ['-nologo', '-t:Build', '-p:Configuration=Release', '-p:EnableWindowsTargeting=true',
         '-p:PublishReadyToRun=false']
XAML_CODE = re.compile(r'<\s*(?:[A-Za-z_][\w.-]*:)?Code[\s>/]')


def load_ratchet():
    spec = importlib.util.spec_from_file_location('ratchet', pathlib.Path(__file__).resolve().parent / 'ratchet.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def generated_ok(name, project, assembly, xaml_stems):
    """Known files the SDK and the WPF markup compiler write under obj/ (matched by exact name, not by pattern)."""
    return (name in {f'{project}.GlobalUsings.g.cs', f'{project}.AssemblyInfo.cs', 'GeneratedInternalTypeHelper.g.cs',
                     f'{assembly}_Content.g.cs'}
            or re.fullmatch(r'\.NETCoreApp,Version=v\d+\.\d+\.AssemblyAttributes\.cs', name) is not None
            or (name.endswith('.g.cs') and name[:-5] in xaml_stems))


def judge_references(project, references, projects):
    """references: posix paths relative to the repo of every ProjectReference; projects: the src/ project names."""
    allowed = {f'src/{name}/{name}.csproj' for name in projects}
    return [f'{project}: <ProjectReference> to {path}, which is not a src/<Name>/<Name>.csproj project. Code it pulls in '
            f'ships with the app but is never judged; move it into src/.' for path in sorted(references)
            if path not in allowed]


def judge(project, compiled, scanned, listed, usings, xaml, assembly):
    """compiled: posix paths relative to the repo of every Compile item; scanned: the ratchet's files for the project;
    listed: every path git would commit; usings: [(identity, static, alias)]; xaml: {path: text} of Page and
    ApplicationDefinition items. Returns the problems."""
    problems = []
    obj = f'src/{project}/obj/'
    xaml_stems = {pathlib.PurePosixPath(path).stem for path in xaml}
    real = set()
    for path in sorted(compiled):
        if path.startswith(obj) and path not in listed:
            if not generated_ok(pathlib.PurePosixPath(path).name, project, assembly, xaml_stems):
                problems.append(f'{project}: {path} is generated by the build but is not a known SDK or WPF output. '
                                f'Write the code in a .cs file in the project instead.')
            continue
        real.add(path)
    for path in sorted(real - set(scanned)):
        problems.append(f'{project}: {path} is compiled, but the ratchet does not read it (outside src/{project}/, not a '
                        f'.cs file, or git-ignored). Put the code in a .cs file inside the project and remove the build '
                        f'item that pulls it in.')
    for path in sorted(set(scanned) - real):
        problems.append(f'{project}: {path} is read by the ratchet but not compiled (removed from the build?). Delete '
                        f'the file or let the project compile it.')
    for identity, static, alias in usings:
        if (static or '').lower() == 'true' or alias:
            problems.append(f'{project}: <Using Include="{identity}"'
                            f'{" Static=true" if (static or "").lower() == "true" else ""}'
                            f'{" Alias=" + alias if alias else ""}> hides a name from the ratchet. Remove it and '
                            f'write the plain call (or a normal `using` line in a .cs file).')
    for path, text in sorted(xaml.items()):
        if XAML_CODE.search(text):
            problems.append(f'{project}: {path} has an x:Code block; C# inside XAML is never read by the ratchet. '
                            f'Move it to the code-behind .cs file.')
    return problems


def relative(path, base):
    try:
        return pathlib.Path(path).resolve().relative_to(base.resolve()).as_posix()
    except ValueError:
        return pathlib.Path(path).resolve().as_posix()


def check(base):
    ratchet = load_ratchet()
    projects, layout_problems = ratchet.layout(base)
    if layout_problems:
        print('COMPILE LIST FAILED: fix the src/ layout first (see the ratchet):\n  ' + '\n  '.join(layout_problems))
        return 1
    listed = {'/'.join(parts) for parts in ratchet.files(base, 'src')}
    problems = []
    for project in projects:
        csproj = f'src/{project}/{project}.csproj'
        run = subprocess.run(['dotnet', 'msbuild', csproj, *BUILD, '-getItem:Compile', '-getItem:Using', '-getItem:Page',
                              '-getItem:ApplicationDefinition', '-getItem:ProjectReference',
                              '-getProperty:AssemblyName'],
                             cwd=str(base), capture_output=True, text=True, encoding='utf-8', errors='replace')
        start = run.stdout.find('{')
        if run.returncode or start < 0:
            tail = '\n'.join((run.stdout + run.stderr).splitlines()[-30:])
            print(f'COMPILE LIST COULD NOT RUN: building {csproj} failed (exit {run.returncode}):\n{tail}')
            return 2
        data = json.loads(run.stdout[start:])
        items = data.get('Items', {})
        compiled = {relative(item['FullPath'], base) for item in items.get('Compile', [])}
        scanned = {path for path in listed
                   if path.startswith(f'src/{project}/') and ratchet.is_csharp(path.rsplit('/', 1)[-1])}
        usings = [(item.get('Identity', ''), item.get('Static', ''), item.get('Alias', ''))
                  for item in items.get('Using', [])]
        xaml = {}
        for item in items.get('Page', []) + items.get('ApplicationDefinition', []):
            path = relative(item['FullPath'], base)
            xaml[path] = pathlib.Path(item['FullPath']).read_text(encoding='utf-8-sig', errors='replace')
        problems += judge(project, compiled, scanned, listed, usings, xaml, data['Properties']['AssemblyName'])
        problems += judge_references(project, {relative(item['FullPath'], base)
                                               for item in items.get('ProjectReference', [])}, projects)
    if problems:
        print(f'COMPILE LIST FAILED: what the build compiles is not what the ratchet reads.\n  Rule: {RULES_DOC}\n  '
              + '\n  '.join(problems))
        return 1
    print(f'COMPILE LIST OK: {len(projects)} projects; every compiled file is a .cs file the ratchet reads, no static or '
          f'alias <Using>, no x:Code, every project reference inside src/')
    return 0


def self_test():
    failures = []

    def expect(name, problems, count, needle=''):
        if len(problems) != count or (needle and not any(needle in p for p in problems)):
            failures.append(f'{name}: expected {count} problem(s) containing {needle!r}, got {problems}')

    p = 'Boo.App'
    obj = f'src/{p}/obj/Release/net10.0-windows/'
    a, b = f'src/{p}/A.cs', f'src/{p}/B.cs'
    xaml = {f'src/{p}/MainWindow.xaml': '<Window x:Class="Boo.App.MainWindow"><Grid/></Window>'}
    sdk = {obj + f'{p}.GlobalUsings.g.cs', obj + f'{p}.AssemblyInfo.cs', obj + '.NETCoreApp,Version=v10.0.AssemblyAttributes.cs',
           obj + 'MainWindow.g.cs', obj + 'GeneratedInternalTypeHelper.g.cs', obj + 'Boo_Content.g.cs'}
    listed = {a, b, f'src/{p}/MainWindow.xaml'}
    plain = [('System', '', ''), ('System.Linq', '', '')]

    def run(compiled=(), scanned=(a, b), usings=plain, pages=None, listed_files=listed):
        return judge(p, set(compiled) | sdk, set(scanned), listed_files, usings, xaml if pages is None else pages, 'Boo')

    expect('exact', run([a, b]), 0)
    names = ['Boo.App', 'Boo.Core']
    expect('reference inside src', judge_references(p, {'src/Boo.Core/Boo.Core.csproj'}, names), 0)
    expect('reference to tools', judge_references(p, {'tools/Boo.LiveProbe/Boo.LiveProbe.csproj'}, names), 1,
           'not a src')
    expect('reference to a nested project', judge_references(p, {'src/Group/Hack/Hack.csproj'}, names), 1, 'not a src')
    expect('outside file compiled', run([a, b, 'docs/x.txt']), 1, 'docs/x.txt is compiled')
    expect('other project file compiled', run([a, b, 'src/Boo.Core/C.cs']), 1, 'is compiled')
    expect('ignored file compiled', run([a, b, f'src/{p}/Ignored.cs']), 1, 'is compiled')
    expect('scanned file not compiled', run([a]), 1, 'not compiled')
    expect('unknown generated file', run([a, b, obj + 'Evil.cs']), 1, 'not a known')
    expect('generated name of a missing page', run([a, b, obj + 'Other.g.cs']), 1, 'not a known')
    expect('git-forced obj file is source', run([a, b, obj + 'Forced.cs'], [a, b, obj + 'Forced.cs'],
                                                listed_files=listed | {obj + 'Forced.cs'}), 0)
    expect('static using', run([a, b], usings=plain + [('System.GC', 'true', '')]), 1, 'Static=true')
    expect('static using, any case', run([a, b], usings=plain + [('System.GC', 'True', '')]), 1, 'Static=true')
    expect('alias using', run([a, b], usings=plain + [('System.GC', '', 'G')]), 1, 'Alias=G')
    expect('x:Code', run([a, b], pages={f'src/{p}/MainWindow.xaml': '<Window><x:Code><![CDATA[ ]]></x:Code></Window>'}),
           1, 'x:Code')
    expect('Code under another prefix', run([a, b], pages={f'src/{p}/MainWindow.xaml': '<Window><q:Code>..</q:Code>'}),
           1, 'x:Code')
    expect('a CodeBlock control is fine', run([a, b], pages={f'src/{p}/MainWindow.xaml': '<Window><l:CodeBlock/>'}), 0)
    if failures:
        print('COMPILE LIST SELF-TEST FAILED:\n  ' + '\n  '.join(failures))
        return 1
    print('COMPILE LIST SELF-TEST OK: outside, ignored, missing and generated files, static and alias usings, x:Code, project references')
    return 0


if __name__ == '__main__':
    if '--self-test' in sys.argv:
        sys.exit(self_test())
    sys.exit(check(root))

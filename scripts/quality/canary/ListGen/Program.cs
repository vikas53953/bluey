using System.Text;
using System.Text.Json;
using Microsoft.Build.Logging.StructuredLogger;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

// Roslyn helper for scripts/quality/banned_apis.py. It reads the real reference assemblies (the ones the canary project
// compiles against: net10.0 + Microsoft.WindowsDesktop.App), so names and overloads come from the compiler, not a guess.
//
//   ListGen generate <refs.txt> <banned-groups.txt> <out BannedSymbols.txt>
//       expand every BAN line into all overloads declared under that name, drop the ALLOW lines, write the list.
//   ListGen bind <refs.txt> <BannedSymbols.txt> <file.cs>...
//       compile the files and print "REF <file>|<line>|<doc id>" for every reference to a banned symbol, resolved the
//       way the analyzer resolves it (original definition; an extension call maps to its static method), and
//       "ERROR <text>" for every compiler error. The Python side compares this with the canary markers.
//   ListGen csc <build.binlog> <project file>
//       print one JSON line per Csc task that MSBuild really ran for that project (from the binary log), with the
//       command line split and parsed by Roslyn's own C# command-line parser (response files expanded), so the Python
//       side judges exactly what the compiler got: tool, analyzers, analyzer configs, additional files, sources,
//       RS0030 options. The binary log is read with MSBuild.StructuredLogger (pinned in ListGen.csproj).
// Exit code 2 means the tool could not do its job (bad input, unknown type, empty group, compile error).

if (args.Length < 3)
{
    Console.Error.WriteLine("usage: ListGen generate <refs> <groups> <out> | ListGen bind <refs> <list> <files...> | "
        + "ListGen csc <binlog> <project>");
    return 2;
}

if (args[0] == "csc")
{
    return CompilerCalls(args[1], args[2]);
}

var references = File.ReadAllLines(args[1])
    .Select(line => line.Trim())
    .Where(line => line.Length > 0)
    .Distinct(StringComparer.Ordinal)
    .OrderBy(line => line, StringComparer.Ordinal)
    .Select(path => (MetadataReference)MetadataReference.CreateFromFile(path))
    .ToList();
if (references.Count == 0)
{
    Console.Error.WriteLine($"no reference assemblies listed in {args[1]}");
    return 2;
}

return args[0] switch
{
    "generate" => Generate(references, args[2], args.Length > 3 ? args[3] : ""),
    "bind" => Bind(references, args[2], args.Skip(3).ToArray()),
    _ => Usage(),
};

static int Usage()
{
    Console.Error.WriteLine("unknown mode; use generate or bind");
    return 2;
}

static int Generate(List<MetadataReference> references, string groupsPath, string outPath)
{
    if (outPath.Length == 0)
    {
        Console.Error.WriteLine("generate needs an output path");
        return 2;
    }

    var compilation = CSharpCompilation.Create("BannedListGen", references: references);
    var output = new StringBuilder();
    output.Append("# GENERATED by scripts/quality/banned_apis.py generate from scripts/quality/canary/banned-groups.txt.\n");
    output.Append("# Do not edit by hand: CI regenerates it from the net10.0 + WindowsDesktop reference packs and fails on any\n");
    output.Append("# difference. Every line has one deliberate call in scripts/quality/canary/Canary.*.cs. Rules: docs/quality/RULES.md\n");

    var allowed = new Dictionary<string, bool>(StringComparer.Ordinal);
    var groups = new List<(string Header, string Kind, string Type, string Member, string Message)>();
    var header = "";
    foreach (var raw in File.ReadAllLines(groupsPath))
    {
        var line = raw.Trim();
        if (line.Length == 0)
        {
            continue;
        }

        if (line.StartsWith('#'))
        {
            if (line.StartsWith("# BOO-", StringComparison.Ordinal))
            {
                header = line;
            }

            continue;
        }

        var bar = line.IndexOf(" | ", StringComparison.Ordinal);
        if (bar < 0)
        {
            Console.Error.WriteLine($"line without ' | ': {line}");
            return 2;
        }

        var head = line[..bar].Trim();
        var message = line[(bar + 3)..].Trim();
        if (message.Contains(';') || message.Length == 0)
        {
            Console.Error.WriteLine($"message must be non-empty and free of ';': {line}");
            return 2;
        }

        if (head.StartsWith("ALLOW ", StringComparison.Ordinal))
        {
            allowed[head[6..].Trim()] = false;
            continue;
        }

        if (!head.StartsWith("BAN ", StringComparison.Ordinal))
        {
            Console.Error.WriteLine($"line must start with BAN or ALLOW: {line}");
            return 2;
        }

        var id = head[4..].Trim();
        if (id.Length < 3 || id[1] != ':' || (id[0] != 'M' && id[0] != 'P'))
        {
            Console.Error.WriteLine($"BAN needs M:<Type>.<Member> or P:<Type>.<Member>: {line}");
            return 2;
        }

        var dot = id.LastIndexOf('.');
        groups.Add((header, id[..1], id[2..dot], id[(dot + 1)..], message));
    }

    var seen = new HashSet<string>(StringComparer.Ordinal);
    var lastHeader = "";
    foreach (var group in groups)
    {
        var type = compilation.GetTypeByMetadataName(group.Type);
        if (type is null)
        {
            Console.Error.WriteLine($"type {group.Type} not found in the reference packs (missing, or declared twice)");
            return 2;
        }

        var members = type.GetMembers(group.Member)
            .Where(member => member.DeclaredAccessibility is Accessibility.Public or Accessibility.Protected
                or Accessibility.ProtectedOrInternal)
            .Where(member => group.Kind == "M" ? member is IMethodSymbol : member is IPropertySymbol)
            .Select(member => WithoutReturnType(DocumentationCommentId.CreateDeclarationId(member)!))
            .OrderBy(docId => docId, StringComparer.Ordinal)
            .ToList();
        if (members.Count == 0)
        {
            Console.Error.WriteLine($"{group.Kind}:{group.Type}.{group.Member} matches no public member");
            return 2;
        }

        if (group.Header != lastHeader)
        {
            output.Append('\n').Append(group.Header).Append('\n');
            lastHeader = group.Header;
        }

        foreach (var docId in members)
        {
            if (allowed.ContainsKey(docId))
            {
                allowed[docId] = true;
                continue;
            }

            if (!seen.Add(docId))
            {
                Console.Error.WriteLine($"{docId} is produced by two BAN lines");
                return 2;
            }

            output.Append(docId).Append(';').Append(group.Message).Append('\n');
        }
    }

    foreach (var (docId, used) in allowed)
    {
        if (!used)
        {
            Console.Error.WriteLine($"ALLOW {docId} names no overload of any BAN line (stale or misspelt)");
            return 2;
        }
    }

    File.WriteAllText(outPath, output.ToString(), new UTF8Encoding(false));
    Console.WriteLine($"wrote {seen.Count} banned symbols to {outPath}");
    return 0;
}

static int CompilerCalls(string binlogPath, string projectFile)
{
    var build = BinaryLog.ReadBuild(binlogPath);
    var wanted = Path.GetFullPath(projectFile);
    var calls = new List<Microsoft.Build.Logging.StructuredLogger.Task>();
    build.VisitAllChildren<Microsoft.Build.Logging.StructuredLogger.Task>(task =>
    {
        var project = task.GetNearestParent<Project>();
        if (task.Name == "Csc" && project is not null
            && string.Equals(Path.GetFullPath(project.ProjectFile), wanted, StringComparison.OrdinalIgnoreCase))
        {
            calls.Add(task);
        }
    });
    var baseDirectory = Path.GetDirectoryName(wanted)!;
    foreach (var task in calls)
    {
        var commandLine = task.CommandLineArguments ?? "";
        var all = CommandLineParser.SplitCommandLineIntoArguments(commandLine, removeHashComments: false).ToList();
        var split = all.FindIndex(arg => Path.GetFileName(arg).ToLowerInvariant() is "csc.dll" or "csc.exe" or "csc");
        var tool = split < 0 ? all : all.Take(split + 1).ToList();
        var rest = split < 0 ? new List<string>() : all.Skip(split + 1).ToList();
        var parsed = CSharpCommandLineParser.Default.Parse(rest, baseDirectory, sdkDirectory: null);
        var options = parsed.CompilationOptions;
        options.SpecificDiagnosticOptions.TryGetValue("RS0030", out var rs0030);
        var line = new Dictionary<string, object?>
        {
            ["target"] = task.GetNearestParent<Target>()?.Name,
            ["tool"] = tool,
            ["responseFiles"] = rest.Where(arg => arg.StartsWith('@')).ToList(),
            ["noConfig"] = rest.Any(arg => arg.Equals("/noconfig", StringComparison.OrdinalIgnoreCase)
                || arg.Equals("-noconfig", StringComparison.OrdinalIgnoreCase)),
            ["analyzerConfigs"] = parsed.AnalyzerConfigPaths.Select(Path.GetFullPath).ToList(),
            ["analyzers"] = parsed.AnalyzerReferences.Select(a => Path.GetFullPath(Path.Combine(baseDirectory, a.FilePath))).ToList(),
            ["additionalFiles"] = parsed.AdditionalFiles.Select(f => Path.GetFullPath(f.Path)).ToList(),
            ["sources"] = parsed.SourceFiles.Select(f => Path.GetFullPath(f.Path)).ToList(),
            ["rs0030Option"] = rs0030 == ReportDiagnostic.Default ? null : rs0030.ToString(),
            ["generalOption"] = options.GeneralDiagnosticOption.ToString(),
            ["warningLevel"] = options.WarningLevel,
            ["ruleSet"] = parsed.RuleSetPath,
            ["skipAnalyzers"] = parsed.SkipAnalyzers,
            ["errors"] = parsed.Errors.Where(d => d.Severity == DiagnosticSeverity.Error).Select(d => d.ToString()).ToList(),
        };
        Console.WriteLine(JsonSerializer.Serialize(line));
    }

    return 0;
}

// Roslyn appends "~ReturnType" to method ids; the analyzer matches the shorter form too (the plan's lines use it, and
// the canary proves every line fires). Overloads never differ by return type alone, and duplicates are refused above.
static string WithoutReturnType(string docId)
{
    var tilde = docId.IndexOf('~', StringComparison.Ordinal);
    return tilde < 0 ? docId : docId[..tilde];
}

static int Bind(List<MetadataReference> references, string listPath, string[] files)
{
    var banned = new HashSet<string>(StringComparer.Ordinal);
    foreach (var raw in File.ReadAllLines(listPath))
    {
        var line = raw.Trim();
        if (line.Length > 0 && !line.StartsWith('#'))
        {
            banned.Add(line.Split(';', 2)[0]);
        }
    }

    var options = new CSharpParseOptions(LanguageVersion.Preview);
    var trees = files.Select(path => CSharpSyntaxTree.ParseText(File.ReadAllText(path), options, path)).ToList();
    var compilation = CSharpCompilation.Create(
        "BannedCanaryBind",
        trees,
        references,
        new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));
    var failed = false;
    foreach (var diagnostic in compilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error))
    {
        Console.WriteLine($"ERROR {diagnostic}");
        failed = true;
    }

    foreach (var tree in trees)
    {
        var model = compilation.GetSemanticModel(tree);
        foreach (var node in tree.GetRoot().DescendantNodes().OfType<SimpleNameSyntax>())
        {
            var symbol = model.GetSymbolInfo(node).Symbol;
            if (symbol is IMethodSymbol method && method.ReducedFrom is not null)
            {
                symbol = method.ReducedFrom;
            }

            if (symbol is null)
            {
                continue;
            }

            var docId = DocumentationCommentId.CreateDeclarationId(symbol.OriginalDefinition);
            docId = docId is null ? null : WithoutReturnType(docId);
            if (docId is not null && banned.Contains(docId))
            {
                var line = node.GetLocation().GetLineSpan().StartLinePosition.Line + 1;
                Console.WriteLine($"REF {tree.FilePath}|{line}|{docId}");
            }
        }
    }

    return failed ? 2 : 0;
}
